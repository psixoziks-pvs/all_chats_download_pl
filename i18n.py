def _merge(locale):
    """Словарь переводов для локали (цепочка уточнения: en <- база <- алиасы)."""
    chain, seen, q = [], set(), [locale]
    while q:
        cur = q.pop(0)
        if not cur or cur in seen:
            continue
        seen.add(cur)
        chain.append(cur)
        alias = ALIASES.get(cur)
        if alias:
            q.append(alias)
        parts = cur.split("-")
        if len(parts) > 1:                       # pt-br -> pt и т.д.
            q.append(parts[0])
    table = dict(TRANSLATIONS.get("en", {}))
    for key in reversed(chain):                  # самые специфичные — последними
        src = TRANSLATIONS.get(key)
        if src:
            table.update(src)
    return table


