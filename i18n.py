def build_manifest():
    """Локализованные поля name/description для plugin.toml.

    Возвращает список пар (key, value): 'name'/'description' — строки
    активной локали, 'name_<locale>'/'description_<locale>' — все
    поддерживаемые языки (локализованные строки манифеста AyuGram; дефисы
    в кодах локалей заменяются на '_' — так требуют TOML-ключи).
    """
    out = []
    for field, key, emoji in (("name", "menu_item", " \U0001F4BE"),
                              ("description", "cmd_help", "")):
        active = _TABLE[key] + emoji
        out.append((field, active))
        for loc in sorted(TRANSLATIONS):
            if not TRANSLATIONS[loc]:
                continue
            val = _merge(loc)[key] + emoji
            out.append(("%s_%s" % (field, loc.replace("-", "_")), val))
    return out


def manifest_toml_lines():
    """Готовые строки для plugin.toml (для генерации/пересборки манифеста)."""
    lines = []
    for k, v in build_manifest():
        esc = v.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('%s = "%s"' % (k, esc))
    return lines
