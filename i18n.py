"""Локализация плагина all_chats_download (i18n).

Язык подбирается автоматически под язык, установленный системно на
устройстве пользователя. Источники языка (в порядке приоритета):

  1. Языковые API хоста AyuGram/Telegrah: ctx.get_language(),
     ctx.language, ctx.settings["language"], tg.getLanguage();
  2. Переменные окружения: ACD_LANG, LANG, LC_ALL, LC_MESSAGES;
  3. Android-локаль (android.multiplewindows / settings);
  4. sys.locale_encoding / default locale Python.

Поддерживаются языки Европы, Северной и Южной Америки, Азии +
международный английский (en — язык по умолчанию).

Также экспортируется build_manifest() — перевод name/description для
plugin.toml (плагины AyuGram могут декларировать локализованные строки
вида `name_ru = "..."` в манифесте).

Тестовый хук: если задана переменная окружения ACD_FORCE_LANG, она имеет
высший приоритет (используется tests/test_plugin.py).
"""

import os

DEFAULT_LOCALE = "en"

# ---------------------------------------------------------------------------
# Алгоритмы подбора языка
# ---------------------------------------------------------------------------

def _norm(code):
    """'pt_BR', 'ru-RU', 'EN ', 'iw' -> 'pt-br', 'ru', 'en', 'he'."""
    if not code:
        return ""
    c = str(code).strip().lower().replace("-", "_")
    parts = c.split("_")
    lang = parts[0]
    # исторические коды Java/Android -> ISO
    lang = {"iw": "he", "in": "id", "ji": "yi", "mo": "ro", "tl": "fil"}.get(
        lang, lang)
    if len(parts) > 1 and parts[1]:
        return "%s-%s" % (lang, parts[1][:6])
    return lang


def _candidates():
    """Список желаемых локалей от пользователя (самая предпочтительная — первой)."""
    out = []

    def add(v):
        v = _norm(v)
        if v and v not in out:
            out.append(v)

    forced = os.environ.get("ACD_FORCE_LANG")
    if forced:
        add(forced)
        return out

    for getter in (
        lambda: _ctx_lang(),
        lambda: os.environ.get("ACD_LANG"),
        lambda: os.environ.get("LC_ALL"),
        lambda: os.environ.get("LC_MESSAGES"),
        lambda: os.environ.get("LANG"),
        lambda: _android_lang(),
        lambda: _python_locale(),
    ):
        try:
            v = getter()
        except Exception:
            v = None
        if isinstance(v, (list, tuple)):
            for x in v:
                add(x)
        else:
            add(v)
    return out


_ctx_ref = None  # последний переданный init_plugin ctx (для подбора языка)


def bind_host(ctx):
    """Плагин вызывает её из init_plugin, чтобы иметь доступ к языку хоста."""
    global _ctx_ref
    _ctx_ref = ctx


def _ctx_lang():
    ctx = _ctx_ref
    if ctx is None:
        return None
    for name in ("get_language", "language", "getLocale", "locale"):
        attr = getattr(ctx, name, None)
        if callable(attr):
            try:
                r = attr()
                if isinstance(r, str):
                    return r
            except Exception:
                pass
        elif isinstance(attr, str):
            return attr
    settings = getattr(ctx, "settings", None)
    if isinstance(settings, dict):
        for k in ("language", "lang", "locale"):
            if isinstance(settings.get(k), str):
                return settings[k]
    tg = getattr(ctx, "tg", None)
    if tg is not None:
        for name in ("getLanguage", "language"):
            attr = getattr(tg, name, None)
            try:
                if callable(attr):
                    r = attr()
                    if isinstance(r, str):
                        return r
                elif isinstance(attr, str):
                    return attr
            except Exception:
                pass
    return None


def _android_lang():
    try:
        from android.utils import convert_python_to_java  # noqa
    except Exception:
        pass
    try:
        import locale as _loc
        return _loc.getlocale()[0] or _loc.getdefaultlocale()[0]
    except Exception:
        return None


def _python_locale():
    try:
        import locale as _loc
        loc = _loc.getlocale()[0]
        if not loc:
            loc = _loc.setlocale(_loc.LC_MESSAGES, "") or ""
            loc = _loc.getlocale()[0] or loc
        return loc
    except Exception:
        return None


def _hit(want):
    """Локаль для одного кода: точное совпадение, алиас, база, семейство."""
    if want in TRANSLATIONS and TRANSLATIONS[want]:
        return want
    a = ALIASES.get(want)
    if a:
        if a in TRANSLATIONS and TRANSLATIONS[a]:
            return a
        a2 = ALIASES.get(a)
        if a2 and a2 in TRANSLATIONS and TRANSLATIONS[a2]:
            return a2
    lang = want.split("-")[0]
    if lang in TRANSLATIONS and TRANSLATIONS[lang]:
        return lang
    la = ALIASES.get(lang)
    if la and la in TRANSLATIONS and TRANSLATIONS[la]:
        return la
    for key in TRANSLATIONS:                     # es-ve -> es-419 и т.п.
        if key.startswith(lang + "-") and TRANSLATIONS[key]:
            return key
    return None


def resolve_locale():
    """Определяет активную локаль плагина (подстраивается под язык устройства)."""
    for want in _candidates():
        hit = _hit(want)
        if hit:
            return hit
    return DEFAULT_LOCALE


